import type { FurnitureDefinition, FurnitureMaterial, FurniturePart } from "./catalog";

type Parts = readonly FurniturePart[];
const box = (id: string, x: number, y: number, z: number, w: number, h: number, d: number, material: FurnitureMaterial = "metal"): FurniturePart => ({ id, shape: "box", position: [x, y, z], size: [w, h, d], material });
const round = (id: string, x: number, y: number, z: number, w: number, h: number, d: number, material: FurnitureMaterial = "metal", shape: FurniturePart["shape"] = "cylinder"): FurniturePart => ({ ...box(id, x, y, z, w, h, d, material), shape, radialSegments: 16 });
const beam = (id: string, x: number, y: number, z: number, w: number, h: number, d: number, dx: number, dz: number, material: FurnitureMaterial = "metal"): FurniturePart => ({ ...box(id, x, y, z, w, h, d, material), lean: [dx, dz] });
const feet = (x: number, z: number, h: number): FurniturePart[] => [-1, 1].flatMap(sx => [-1, 1].map(sz => box(`foot-${sx}-${sz}`, sx * x, h / 2, sz * z, .09, h, .09, "dark")));
const define = (id: string, name: string, category: "workshop" | "collectible", width: number, depth: number, height: number, price: number, level: number, color: string, description: string, label: string): FurnitureDefinition => Object.freeze({
  id, name, category, width, depth, height, price, level, color, description, neonColor: "#00f0ff",
  interactions: Object.freeze([Object.freeze(category === "workshop"
    ? { id: "craft" as const, label, screen: "crafting" as const, activity: "working" as const }
    : { id: "display" as const, label, screen: "achievements" as const })]),
});

